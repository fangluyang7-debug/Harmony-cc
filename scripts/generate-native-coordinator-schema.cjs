// Generate the native database schema from the same migrations used on Windows.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),source=path.join(root,'services/coordinator/prisma/migrations');
const migrations=fs.readdirSync(source).filter(n=>fs.existsSync(path.join(source,n,'migration.sql'))).sort().map(id=>{
 const sql=fs.readFileSync(path.join(source,id,'migration.sql'),'utf8');
 if(/\b(TRIGGER|BEGIN|COMMIT|ROLLBACK)\b/i.test(sql.replace(/--[^\n]*/g,'')))throw Error('MIGRATION_REQUIRES_SQL_PARSER:'+id);
 const statements=sql.replace(/--[^\n]*/g,'').split(';').map(s=>s.trim()).filter(Boolean);
 return {id,digest:crypto.createHash('sha256').update(sql).digest('hex'),statements};
});
const output='// Generated by scripts/generate-native-coordinator-schema.cjs.\nexport interface CoordinatorMigration {id:string;digest:string;statements:string[];}\nexport const coordinatorMigrations:CoordinatorMigration[]='+JSON.stringify(migrations,null,2)+';\n';
fs.writeFileSync(path.join(root,'apps/harmony/scheduler/src/main/ets/v2/coordinator/CoordinatorSchema.ets'),output);
console.log('Generated '+migrations.length+' native coordinator migrations');
